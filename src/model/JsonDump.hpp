#pragma once

#include <string>

#include <nlohmann/json.hpp>


namespace h2agent
{
namespace model
{

/**
 * Json text of a document holding received or user data (events, sequences,
 * vault, failures, logs). A text which is not UTF-8 (a body or header with any
 * byte, a command output) makes the strict dump throw: here the invalid bytes
 * become U+FFFD and the rest is kept, so one bad value never hides the others
 * nor reaches an I/O thread as an exception.
 *
 * @param j Json document
 * @param indent Indentation (-1: compact)
 */
inline std::string dumpJson(const nlohmann::json &j, int indent = -1) {
    return j.dump(indent, ' ', false, nlohmann::json::error_handler_t::replace);
}

}
}
